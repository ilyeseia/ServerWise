/** Returns a function that turns a server error code into a translated message. */
export function useErrorText() {
  const t = useTranslations("Crm.errors");
  return (code: string) =>
    t(((KNOWN as readonly string[]).includes(code) ? code : "UNKNOWN") as Known);
}
